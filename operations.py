"""
operation
==========
Contains basic arithmetic operations: addition, subtraction, multiplication, division.
"""
def add(a, b):
#    add two numbers
    return a + b

def subtract(a, b):
#   subtract two numbers
    return a - b


def multiply(a, b):
#   multiply two numbers
    return a * b


def divide(a, b):
#   divide two numbers
    return a / b 